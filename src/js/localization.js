export class LocalizationEngine {
  constructor() {
    this.currentLang = localStorage.getItem("jamin_lang") || "ne"; // Default to Nepali
  }

  setLanguage(lang) {
    if (lang === "en" || lang === "ne") {
      this.currentLang = lang;
      localStorage.setItem("jamin_lang", lang);
      this.translateDOM();
    }
  }

  translate(key) {
    return TRANSLATIONS[this.currentLang][key] || TRANSLATIONS["en"][key] || key;
  }

  translateDOM() {
    const elements = document.querySelectorAll("[data-i18n]");
    elements.forEach(el => {
      const key = el.getAttribute("data-i18n");
      const translation = this.translate(key);
      
      if (el.tagName === "INPUT" && (el.type === "placeholder" || el.placeholder)) {
        el.placeholder = translation;
      } else {
        el.innerHTML = translation;
      }
    });

    // Toggle active state on language switcher buttons if they exist
    const switchers = document.querySelectorAll(".lang-switch-btn");
    switchers.forEach(btn => {
      if (btn.getAttribute("data-lang") === this.currentLang) {
        btn.classList.add("active");
      } else {
        btn.classList.remove("active");
      }
    });

    // Set font family standard for body
    if (this.currentLang === "ne") {
      document.body.style.fontFamily = "'Mukta', sans-serif";
    } else {
      document.body.style.fontFamily = "'Outfit', sans-serif";
    }
  }

  // Format currency in Nepalese Rupees (Lakhs/Crores grouping)
  formatNPR(amount) {
    const num = Number(amount);
    if (isNaN(num)) return "NPR 0";
    
    // Nepalese formatting rule: Lakh = 100,000 (1,00,000), Crore = 10,000,000 (1,00,00,000)
    let formatted = "";
    if (this.currentLang === "ne") {
      formatted = "रु. " + this.toNepaliNumerals(num.toLocaleString("en-IN"));
    } else {
      formatted = "NPR " + num.toLocaleString("en-IN");
    }
    return formatted;
  }

  // Convert English numbers (123...) to Nepali Unicode (१२३...)
  toNepaliNumerals(str) {
    const nepaliDigits = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"];
    return String(str).replace(/[0-9]/g, match => nepaliDigits[Number(match)]);
  }

  // Nepali Date formatter mock (Gregorian -> Bikram Sambat simplified BS)
  getBSDateString() {
    const today = new Date();
    // Simplified BS conversion offset: Add approx 56 years, 8 months, 17 days
    const bsYear = today.getFullYear() + 56;
    const bsMonthIndex = (today.getMonth() + 8) % 12;
    const bsDay = (today.getDate() + 17) % 30 + 1;
    
    const bsMonthsEN = [
      "Baishakh", "Jestha", "Ashadh", "Shrawan", "Bhadra", "Ashwin", 
      "Kartik", "Mangsir", "Poush", "Magh", "Falgun", "Chaitra"
    ];
    
    const bsMonthsNE = [
      "वैशाख", "जेठ", "असार", "साउन", "भदौ", "असोज", 
      "कात्तिक", "मंसिर", "पुस", "माघ", "फागुन", "चैत"
    ];

    if (this.currentLang === "ne") {
      return `${this.toNepaliNumerals(bsYear)} ${bsMonthsNE[bsMonthIndex]} ${this.toNepaliNumerals(bsDay)}`;
    } else {
      return `${bsDay} ${bsMonthsEN[bsMonthIndex]} ${bsYear} BS`;
    }
  }
}
